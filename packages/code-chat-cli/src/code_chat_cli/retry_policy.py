"""Gemini API のリトライ方針 (試行回数, 待ち時間) を定義するモジュール."""


class RetryPolicy:
    """Gemini API の一時的なエラー (503 / 429 など) をリトライするときの設定値を保持するクラス.

    待ち時間は, 指数バックオフにジッター (ランダムな揺らぎ) を加えて決めます.
    API が推奨待機時間 (`retryDelay`) を返した場合は, それを優先します.
    """

    MAX_ATTEMPTS = 5
    """初回を含む最大試行回数."""

    INITIAL_DELAY = 1.0
    """最初のリトライまでの待ち時間 (秒)."""

    MAX_DELAY = 60.0
    """リトライ間の待ち時間の上限 (秒)."""

    EXP_BASE = 2.0
    """リトライのたびに待ち時間を何倍にするか (指数バックオフの底)."""

    JITTER = 1.0
    """待ち時間に加える, ランダムな揺らぎの大きさ (秒). 同時に再試行するクライアントの集中を避ける."""

    RETRY_DELAY_MARGIN = 1.0
    """API が推奨する待機時間 (`retryDelay`) に, 余裕として加える秒数."""
